const NOTE_FIELDS=['accessNotes','accessNote','collectionNotes','networkNotes','checkNotes','languageScope','sourceNotes','languageNotes','sourceCheckMethod','summaryMethod','sourceStatus'];
const SUPPORTED_LANGUAGES=new Set(['en','fr','es']);
const localeCode=language=>String(language||'en').toLowerCase().split(/[-_]/)[0];
const hasText=value=>typeof value==='string'&&value.trim().length>0;

// Return a fresh view of a profile. Keep canonical records in English for edits,
// taxonomy filters and indexing; never write this presentation object to storage.
// New sources may supply translations directly as source.translations.{fr,es}.
// A catalogue translation is ignored after its original description changes.
export function localiseSource(source,language='en'){
  const requestedLanguage=localeCode(language);
  const lang=SUPPORTED_LANGUAGES.has(requestedLanguage)?requestedLanguage:'en';
  const originalAbout=source.originalAbout??source.about;
  const originalName=source.originalName||source.name;
  const originalLanguage=source.translation?.originalLanguage||source.descriptionLanguage||'en';
  const result={...source,name:originalName,about:originalAbout,originalName,originalAbout};
  const base=SOURCE_TRANSLATIONS[source.id];
  const embeddedOriginal=source.translations?.en?.about;
  const embedded=!hasText(embeddedOriginal)||embeddedOriginal===originalAbout?source.translations?.[lang]:undefined;
  const stored=base?.originalAbout===originalAbout?base[lang]:undefined;
  const translated={...stored,...embedded};
  const available=lang!=='en'&&hasText(translated.about);
  const untranslatedFields=[];
  const originalFields=['name','owner','brandName','sourceTitle'];
  if(available){
    for(const field of ['name','about','affiliation'])if(hasText(translated[field]))result[field]=translated[field];
    result.descriptionLanguage=lang;
    for(const field of NOTE_FIELDS){
      if(!hasText(source[field]))continue;
      const note=translated[field]||SOURCE_NOTE_TRANSLATIONS[source[field]]?.[lang];
      if(hasText(note))result[field]=note;
      else untranslatedFields.push(field);
    }
    if(Array.isArray(source.reviewNotes))result.reviewNotes=source.reviewNotes.map((note,index)=>{
      const local=translated.reviewNotes?.[index]||SOURCE_NOTE_TRANSLATIONS[note]?.[lang];
      if(hasText(local))return local;
      untranslatedFields.push(`reviewNotes.${index}`);return note;
    });
    if(Array.isArray(source.publicationLinks))result.publicationLinks=source.publicationLinks.map((publication,index)=>{
      const local=translated.publicationLinks?.[index]||{};
      const detail=local.detail||SOURCE_NOTE_TRANSLATIONS[publication.detail]?.[lang];
      if(hasText(publication.detail)&&!hasText(detail))untranslatedFields.push(`publicationLinks.${index}.detail`);
      // Paper titles remain recognisable; these links do not translate papers.
      originalFields.push(`publicationLinks.${index}.title`);
      return {...publication,...local,originalTitle:publication.originalTitle||publication.title,...(hasText(detail)?{detail}:{})};
    });
  }else result.descriptionLanguage=originalLanguage;
  result.translation={
    language:lang,requestedLanguage,originalLanguage,available,isTranslated:available,
    assisted:available,originalFields,untranslatedFields,
    note:lang==='en'?'':SOURCE_TRANSLATION_COPY[lang][available?'translated':'pending']
  };
  return result;
}

// Add this to the metadata search index; never replace original-language text.
// This includes editorial names/descriptions, not externally fetched papers.
export function sourceTranslationSearchText(source){
  return ['fr','es'].flatMap(lang=>{
    const profile=localiseSource(source,lang);
    return profile.translation.available?[profile.name,profile.about]:[];
  }).join(' ');
}
