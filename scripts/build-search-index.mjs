import {writeFile,readFile} from 'node:fs/promises';
import {SOURCES} from '../public/data.js';
import {buildSearchEntry} from '../public/search.js';
const file=new URL('../public/search-index.js',import.meta.url);
const content='// Generated by scripts/build-search-index.mjs.\nexport const INDEX='+JSON.stringify(Object.fromEntries(SOURCES.map(s=>[s.id,buildSearchEntry(s)])))+';\n';
if(process.argv.includes('--check')){if(await readFile(file,'utf8')!==content)throw Error('Search index is stale: run node scripts/build-search-index.mjs');}
else await writeFile(file,content);
